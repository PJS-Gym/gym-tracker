// Copies the PJS Gym design system from /design-system into src/design-system.
//
// The Next app is built with frontend/ as its root, so it cannot import files from the repo root.
// /design-system stays the source of truth: never edit src/design-system by hand, change the
// design system and run `bun run sync:ds` again.
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const frontend = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(frontend, "..", "design-system");
const target = join(frontend, "src", "design-system");

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });

// Tailwind's CSS resolver reads `@import "tokens/x.css"` as a package name, so make the paths relative.
writeFileSync(
  join(target, "styles.css"),
  readFileSync(join(source, "styles.css"), "utf8").replace(/@import "(?!\.{0,2}\/)([^"]+)"/g, '@import "./$1"'),
);
cpSync(join(source, "tokens"), join(target, "tokens"), { recursive: true });
cpSync(join(source, "assets", "fonts"), join(target, "assets", "fonts"), { recursive: true });
cpSync(join(source, "components"), join(target, "components"), {
  recursive: true,
  filter: (path) => !/\.(prompt\.md|card\.html)$/.test(path),
});

// One client-side entry point, so app code imports `@/design-system` and gets the .d.ts types.
const values = [];
const types = [];
const groups = readdirSync(join(target, "components"), { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

for (const group of groups) {
  const dir = join(target, "components", group);
  for (const file of readdirSync(dir).filter((name) => name.endsWith(".d.ts")).sort()) {
    const dts = readFileSync(join(dir, file), "utf8");
    const from = "./" + relative(target, join(dir, file.replace(/\.d\.ts$/, ""))).replaceAll("\\", "/");
    const valueNames = [...dts.matchAll(/^export (?:const|function) (\w+)/gm)].map((m) => m[1]);
    const typeNames = [...dts.matchAll(/^export (?:interface|type) (\w+)/gm)].map((m) => m[1]);
    if (valueNames.length) values.push(`export { ${[...new Set(valueNames)].join(", ")} } from "${from}";`);
    if (typeNames.length) types.push(`export type { ${[...new Set(typeNames)].join(", ")} } from "${from}";`);
  }
}

writeFileSync(
  join(target, "index.ts"),
  [
    '"use client";',
    "",
    "// Generated by scripts/sync-design-system.mjs. Do not edit.",
    "",
    ...values,
    "",
    ...types,
    "",
  ].join("\n"),
);

console.log(`Synced design system into ${relative(process.cwd(), target) || "."}`);
